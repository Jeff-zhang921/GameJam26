async (page) => {
  const browser = page.context().browser();
  const first = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const second = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const host = await first.newPage(), guest = await second.newPage();
  const errors = [], protocolErrors = [];
  let playing = false;
  for (const tab of [host, guest]) tab.on('pageerror', error => errors.push(error.message));
  for (const tab of [host, guest]) tab.on('websocket', socket => socket.on('framereceived', frame => {
    const message = JSON.parse(String(frame.payload));
    if (playing && message.type === 'error') protocolErrors.push(message.code);
  }));
  const snapshot = tab => tab.evaluate(() => window.__moonclock.snapshot());
  const connection = tab => tab.evaluate(() => window.__moonclock.connection());
  const send = (tab, action) => tab.evaluate(value => window.__moonclock.dispatch(value), action);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  try {
  await host.goto('http://127.0.0.1:4173/');
  await host.evaluate(() => sessionStorage.setItem('moonclock-online', JSON.stringify({ code: '00', playerId: 'expired', token: 'invalid' })));
  await host.reload();
  await host.locator('.online-error:not([hidden])').waitFor({ state: 'visible' });
  await host.getByRole('button', { name: 'Leave Room', exact: true }).click();
  await host.getByTestId('create-room').waitFor({ state: 'visible' });
  await host.getByTestId('create-room').click();
  await host.getByTestId('room-code').waitFor({ state: 'visible' });
  const code = await host.getByTestId('room-code').innerText();
  await guest.goto('http://127.0.0.1:4173/');
  await guest.getByTestId('join-room').click();
  await guest.getByTestId('room-code-input').fill(code === '00' ? '01' : '00');
  await guest.getByTestId('join-room-submit').click();
  await guest.locator('.online-error:not([hidden])').waitFor({ state: 'visible' });
  check(await guest.getByTestId('room-code-input').isEnabled(), 'Failed join must remain editable');
  await guest.getByTestId('room-code-input').fill(code.toLowerCase());
  await guest.getByTestId('join-room-submit').click();
  await guest.getByTestId('room-code').waitFor({ state: 'visible' });
  await host.getByTestId('character-still').click();
  await guest.waitForFunction(() => document.querySelector('[data-testid="character-still"]').disabled);
  await guest.getByTestId('character-bloom').click();
  check(await host.getByTestId('start-game').isDisabled(), 'Unready start must be disabled');
  await host.getByTestId('ready').click(); await guest.getByTestId('ready').click();
  await host.waitForFunction(() => !document.querySelector('[data-testid="start-game"]').disabled);
  await host.screenshot({ path: '.audit/online-lobby.png' });
  await host.getByTestId('start-game').click();
  for (const tab of [host, guest]) await tab.waitForFunction(() => window.__moonclock.connection().room.status === 'PLAYING');
  playing = true;
  const initial = [await snapshot(host), await snapshot(guest)];
  check(initial[0].actors.every((actor, i) => actor.x === initial[1].actors[i].x && actor.y === initial[1].actors[i].y), 'Initial worlds differ');
  await host.locator('#game').focus(); await host.keyboard.down('KeyD');
  await host.waitForTimeout(180); await host.keyboard.up('KeyD'); await host.waitForTimeout(100);
  const moved = [await snapshot(host), await snapshot(guest)];
  check(moved[0].actors[0].x > initial[0].actors[0].x && moved[0].actors[0].x === moved[1].actors[0].x, 'Movement not shared');
  await guest.locator('#game').focus(); await guest.keyboard.down('Space'); await guest.waitForTimeout(130);
  check((await snapshot(host)).actors[1].animation.name === 'jump', 'Jump animation not shared');
  await guest.keyboard.up('Space');
  await send(host, { type: 'ability' }); await host.waitForTimeout(60);
  const frozen = await snapshot(guest), cast = frozen.actors[0].animation;
  check(frozen.objects[0].frozen && cast.name === 'cast', 'Freeze or cast not shared');
  await host.waitForTimeout(60);
  check((await snapshot(guest)).actors[0].animation.startTick === cast.startTick, 'Snapshots restart cast animation');
  // Still's Freeze Area is shared state (Bloom no longer releases crates; areas fade on their own).
  check((await snapshot(host)).freezeAreas.length === 1, 'Freeze Area not shared');
  const identity = await connection(guest);
  await guest.locator('#game').focus(); await guest.keyboard.press('Tab');
  check((await connection(guest)).actor === identity.actor, 'Tab changed online role');
  await guest.goto('about:blank');
  await host.waitForFunction(() => window.__moonclock.connection().room.suspended);
  const stopped = (await snapshot(host)).tick; await host.waitForTimeout(120);
  check((await snapshot(host)).tick === stopped, 'Disconnect did not suspend simulation');
  await guest.goto('http://127.0.0.1:4173/');
  await guest.waitForFunction(() => window.__moonclock.connection().status === 'connected' && !window.__moonclock.connection().room.suspended);
  check((await connection(guest)).playerId === identity.playerId, 'Reconnect changed player identity');
  check((await connection(guest)).room.players.length === 2, 'Reconnect duplicated player');
  await send(host, { type: 'restart' });
  await host.waitForFunction(() => window.__moonclock.snapshot().tick < 20 && window.__moonclock.snapshot().actors[0].x === 180);
  await send(host, { type: 'move', dir: 1 });
  await host.waitForFunction(() => window.__moonclock.snapshot().actors[0].x > 270);
  await send(host, { type: 'grab' });
  await host.waitForFunction(() => window.__moonclock.snapshot().actors[0].carrying === 'crate-0');
  await host.waitForFunction(() => window.__moonclock.snapshot().actors[0].x >= 418);
  await send(host, { type: 'move', dir: 0 }); await send(host, { type: 'grab' });
  await host.waitForFunction(() => window.__moonclock.snapshot().events.some(event => event.kind === 'throw'));
  const thrown = (await snapshot(host)).events.findLast(event => event.kind === 'throw').tick;
  await host.waitForFunction(tick => window.__moonclock.snapshot().tick >= tick + 18, thrown);
  await send(host, { type: 'ability', target: 'crate-0' });
  await host.waitForFunction(() => window.__moonclock.snapshot().objects[0].frozen);
  await send(host, { type: 'move', dir: 1 }); await send(host, { type: 'jump' });
  await host.waitForFunction(() => window.__moonclock.snapshot().actors[0].on === 'crate-0', null, { timeout: 5000 });
  await send(host, { type: 'jumpRelease' }); await send(host, { type: 'jump' });
  await host.waitForFunction(() => window.__moonclock.snapshot().status === 'won', null, { timeout: 6000 });
  await guest.waitForFunction(() => window.__moonclock.snapshot().status === 'won');
  check(await host.getByTestId('next').isVisible(), 'Win screen hidden by disconnect overlay');
  check(await guest.getByTestId('next').isDisabled(), 'Guest may not advance level');
  await host.screenshot({ path: '.audit/online-win.png' });
  await host.getByTestId('next').click();
  for (const tab of [host, guest]) await tab.waitForFunction(() => window.__moonclock.snapshot().level === 1 && document.querySelector('.scene-veil').hidden);
  const next = [await snapshot(host), await snapshot(guest)];
  check(next[0].level === next[1].level, 'Next level diverged');
  await send(guest, { type: 'move', dir: 1 });
  check(next[1].actors[1].carrying === 'seed-starter', 'Bloom did not start with the seed');
  await guest.waitForFunction(() => window.__moonclock.snapshot().actors[1].x >= 590);
  await send(guest, { type: 'move', dir: 0 }); await send(guest, { type: 'grab' });
  await guest.waitForFunction(() => window.__moonclock.snapshot().objects.some(o => o.kind === 'plant'));
  for (let speed = 1; speed <= 3; speed++) {
    await send(guest, { type: 'ability' });
    await host.waitForFunction(value => window.__moonclock.snapshot().objects.some(o => o.kind === 'plant' && o.speed === value), speed);
  }
  const plant = (await snapshot(host)).objects.find(o => o.kind === 'plant');
  check(plant.speed === 3, 'Bloom multiplier changed');
  check(errors.length === 0, errors.join('\n'));
  check(protocolErrors.length === 0, protocolErrors.join(', '));
  const result = { room: code, createdJoined: true, sharedStart: true, movement: true, jumpAnimation: true, castStable: true, sharedFreezeRelease: true, tokenReconnect: true, sharedCompletionAndNext: true, bloomMaxSpeed: plant.speed, errors, protocolErrors };
  await guest.screenshot({ path: '.audit/online-gameplay.png' });
  await host.getByRole('button', { name: 'Leave online room' }).click();
  await guest.getByRole('button', { name: 'Leave Room', exact: true }).click();
  return result;
  } finally {
    await first.close(); await second.close();
  }
}
